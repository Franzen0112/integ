/**
 * Builds supabase-config.js from environment variables (Vercel / CI).
 * Only writes ANON key to the browser config — never service_role.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'supabase-config.js');

const PROJECT_ID = process.env.SUPABASE_PROJECT_ID || 'eeagyngzbzcpqxptnqvy';
const SUPABASE_URL =
  process.env.SUPABASE_URL || `https://${PROJECT_ID}.supabase.co`;
const SUPABASE_ANON_KEY =
  process.env.SUPABASE_ANON_KEY ||
  'eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJpc3MiOiJzdXBhYmFzZSIsInJlZiI6ImVlYWd5bmd6YnpjcHF4cHRucXZ5Iiwicm9sZSI6ImFub24iLCJpYXQiOjE3NjcyNzk1MTUsImV4cCI6MjA4Mjg1NTUxNX0.PY_4TUkQoDvwhUKyYl2lIcCvfA6mgCStp9h657IMq0g';

if (!SUPABASE_ANON_KEY || SUPABASE_ANON_KEY.length < 20) {
  console.error('SUPABASE_ANON_KEY is missing or invalid.');
  process.exit(1);
}

if (process.env.SUPABASE_SERVICE_ROLE) {
  console.warn(
    'Warning: SUPABASE_SERVICE_ROLE is set but will NOT be written to supabase-config.js (browser-safe build).'
  );
}

const content = `// AUTO-GENERATED by scripts/generate-supabase-config.js — do not edit by hand on Vercel builds
// Project ID: ${PROJECT_ID}
// Regenerate locally: npm run build

const SUPABASE_URL = '${SUPABASE_URL}';
const SUPABASE_ANON_KEY = '${SUPABASE_ANON_KEY}';

const AUTH_STORAGE_KEY = 'jjrk-studio-auth';

function getAppOrigin() {
  if (typeof window !== 'undefined' && window.location && window.location.origin) {
    const origin = window.location.origin;
    if (origin.startsWith('http://') || origin.startsWith('https://')) {
      return origin.replace(/\\/$/, '');
    }
  }
  return 'http://127.0.0.1:8080';
}

function getAuthRedirectUrl() {
  return getAppOrigin() + '/auth/callback.html';
}

function getAuthCallbackUrls() {
  var origin = getAppOrigin();
  return [
    origin + '/auth/callback.html',
    origin + '/auth/callback',
    origin + '/login.html',
    origin + '/**'
  ];
}

function initializeSupabaseClient() {
  if (typeof window === 'undefined') return false;

  if (window.supabaseClient) {
    return true;
  }

  try {
    if (window.supabase && typeof window.supabase.createClient === 'function') {
      window.supabaseClient = window.supabase.createClient(SUPABASE_URL, SUPABASE_ANON_KEY, {
        auth: {
          persistSession: true,
          autoRefreshToken: true,
          detectSessionInUrl: true,
          storageKey: AUTH_STORAGE_KEY
        }
      });
      return true;
    }
  } catch (error) {
    console.error('Error initializing Supabase:', error);
  }
  return false;
}

function waitForSupabase(maxWaitMs) {
  maxWaitMs = maxWaitMs || 8000;
  return new Promise(function(resolve, reject) {
    if (window.supabaseClient) {
      resolve(window.supabaseClient);
      return;
    }

    var elapsed = 0;
    var step = 100;

    function tick() {
      initializeSupabaseClient();
      if (window.supabaseClient) {
        resolve(window.supabaseClient);
        return;
      }
      elapsed += step;
      if (elapsed >= maxWaitMs) {
        reject(new Error('Could not connect to Supabase. Check your internet and refresh the page.'));
        return;
      }
      setTimeout(tick, step);
    }

    tick();
  });
}

if (typeof window !== 'undefined') {
  window.getAppOrigin = getAppOrigin;
  window.getAuthRedirectUrl = getAuthRedirectUrl;
  window.getAuthCallbackUrls = getAuthCallbackUrls;
  window.initializeSupabaseClient = initializeSupabaseClient;
  window.waitForSupabase = waitForSupabase;

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initializeSupabaseClient);
  } else {
    initializeSupabaseClient();
  }
}
`;

fs.writeFileSync(OUT, content, 'utf8');
console.log('Generated supabase-config.js for project:', PROJECT_ID);
